// Writes port/src/rom/painting_data.luau: one PaintingsH.Painting record per `struct Painting NAME = { ... };` of
// levels/castle_inside, levels/hmc and levels/ttm (decision painting-data-records). The initializer is positional; a float literal
// is stored as the f32 value it denotes. The display list, texture map and texture array fields are the segmented addresses in the
// names of the symbols the initializer names (`inside_castle_seg7_painting_dl_07023050` is 0x07023050).
//
// Usage: node native/tools/gen_painting_data.mjs <project root>
import fs from "node:fs";
import path from "node:path";

const Root = process.argv[2];
const Sources = ["levels/castle_inside/painting.inc.c", "levels/hmc/areas/1/painting.inc.c", "levels/ttm/areas/1/painting.inc.c"];
const Output = path.join(Root, "port/src/rom/painting_data.luau");
const Constants = { PAINTING_IMAGE: 0, PAINTING_ENV_MAP: 1, RIPPLE_TRIGGER_PROXIMITY: 10, RIPPLE_TRIGGER_CONTINUOUS: 20 };

// Field names in the order of struct Painting (paintings.h).
const Fields = [
	"id", "imageCount", "textureType", "lastFloor", "currFloor", "floorEntered", "state", "pitch", "yaw", "posX", "posY", "posZ",
	"currRippleMag", "passiveRippleMag", "entryRippleMag", "rippleDecay", "passiveRippleDecay", "entryRippleDecay",
	"currRippleRate", "passiveRippleRate", "entryRippleRate", "dispersionFactor", "passiveDispersionFactor", "entryDispersionFactor",
	"rippleTimer", "rippleX", "rippleY", "normalDisplayList", "textureMaps", "textureArray", "textureWidth", "textureHeight", "rippleDisplayList", "rippleTrigger", "alpha",
	"marioWasUnder", "marioIsUnder", "marioWentUnder", "size",
];
const Addresses = new Set(["normalDisplayList", "textureMaps", "textureArray", "rippleDisplayList"]);
const Floats = new Set(Fields.filter((Name) => !Addresses.has(Name) && !["id", "imageCount", "textureType", "lastFloor", "currFloor", "floorEntered", "state", "textureWidth", "textureHeight", "rippleTrigger", "alpha", "marioWasUnder", "marioIsUnder", "marioWentUnder"].includes(Name)));

function Value(Token, Name) {
	if (Token in Constants) {
		return Constants[Token];
	}

	if (Addresses.has(Name)) {
		const Address = /_(07[0-9A-F]{6})$/.exec(Token);

		if (Address === null) {
			throw new Error(`${Name}: ${Token} has no segmented address in its name`);
		}

		return `0x${Address[1]}`;
	}

	if (Floats.has(Name)) {
		return String(Math.fround(Number(Token.replace(/f$/, ""))));
	}

	return String(Number(Token));
}

const Records = [];

for (const Source of Sources) {
	const Text = fs.readFileSync(path.join(Root, "reference", Source), "utf8");
	const Pattern = /struct Painting (\w+) = \{([\s\S]*?)\n\};/g;

	for (const Match of Text.matchAll(Pattern)) {
		const Body = Match[2].replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
		const Tokens = Body.split(",").map((Token) => Token.trim()).filter((Token) => Token !== "");

		if (Tokens.length !== Fields.length) {
			throw new Error(`${Match[1]}: ${Tokens.length} initializers, expected ${Fields.length}`);
		}

		const Lines = [];

		Fields.forEach((Name, Index) => {
			Lines.push(`\t\t${Name} = ${Value(Tokens[Index], Name)},`);
		});

		const First = Text.slice(0, Match.index).split("\n").length;
		const Last = First + Match[0].split("\n").length - 1;

		Records.push({ Name: Match[1], Source, Range: `L${First}-${Last}`, Lines });
	}
}

const Out = [
	"--!strict",
	"--!optimize 2",
	"",
	"--[[",
	"\tGenerated by native/tools/gen_painting_data.mjs: the Painting records of the level data of the castle, Hazy Maze and Tall Tall",
	"\tMountain (painting-data-records). Each painting is mutable game state; its display lists, texture maps and texture arrays",
	"\tare the segmented addresses of the level data (read where the painting is drawn).",
	"]]",
	"",
	'const PaintingsH = require("../game/paintings_h")',
	"",
	"-- from levels/castle_inside/painting.inc.c:data",
	"const painting_data = {",
];

for (const Record of Records) {
	Out.push(`\t-- from ${Record.Source}:${Record.Name} ${Record.Range}`);
	Out.push(`\t${Record.Name} = {`);
	Out.push(...Record.Lines);
	Out.push("\t} :: PaintingsH.Painting,");
}

Out.push("}", "", "return painting_data", "");
fs.writeFileSync(Output, Out.join("\n"));
console.log(`${Records.length} paintings written to ${Output}`);
