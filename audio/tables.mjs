// Writes rom-tool/sound/tables.js (node audio/tables.mjs): what the sound generator needs to know about the game's sounds that is not in the
// ROM's sound data, read from the decompilation checked out in reference/: the sound effects (include/sounds.h), the sequences (include/seq_ids.h),
// the sequence player each runs on and the audio settings preset of its level (the level scripts). The file is committed: only a change of the
// decompilation needs this.
import fs from "node:fs";
import path from "node:path";

import { parsePresets, parseSequences, parseSounds, sequencePlayer } from "./lib/gamedata.mjs";
import { ROOT } from "./lib/paths.mjs";

const sounds = parseSounds().map(({ key, name, bits, continuous, aliases }) => ({ key, name, bits, continuous, aliases }));
const sequences = parseSequences();
const presetOf = parsePresets(sequences);
const entries = sequences.map((sequence) => ({ id: sequence.id, name: sequence.name, player: sequencePlayer(sequence), preset: presetOf(sequence.id) }));

const lines = (items) => items.map((item) => `  ${JSON.stringify(item)},`).join("\n");

const text = `// Generated by audio/tables.mjs from the decompilation: do not edit.

// The sound effects: key is "<bank>_<id>", bits the sound as the game requests it, continuous when the game requests it every frame
export const SOUNDS = [
${lines(sounds)}
];

// The music sequences: the sequence player each runs on and the audio settings preset of its level
export const SEQUENCES = [
${lines(entries)}
];
`;

fs.writeFileSync(path.join(ROOT, "rom-tool", "sound", "tables.js"), text);
console.log(`${sounds.length} sounds, ${entries.length} sequences`);
